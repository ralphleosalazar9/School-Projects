    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) taskDisplay.getModel();
        int selectedRow = taskDisplay.getSelectedRow();
        //Something wrong on Deleting.
        if (selectedRow != -1) {
            
            int choice = javax.swing.JOptionPane.showConfirmDialog(this, "Are you sure you want to delete task?",
                    "Confirm Delete", javax.swing.JOptionPane.YES_NO_OPTION);
            
            if (choice == javax.swing.JOptionPane.YES_OPTION) {
                //model.removeRow(selectedRow);
                try {
                    model.removeRow(selectedRow);
                    BufferedWriter writer = new BufferedWriter(new FileWriter("Task.txt", false));
                    for (int i = 0; i < model.getRowCount(); i++) {
                        String deleteSubject = model.getValueAt(i, 0).toString();
                        String deleteTask = model.getValueAt(i, 1).toString();
                        String deleteDate = model.getValueAt(i, 2).toString();
                        String deleteStatus = model.getValueAt(i, 3).toString();
                        
                        writer.write(deleteSubject + "," + deleteTask + "," + deleteDate + "," + deleteStatus);
                        writer.newLine();
                    }
                    writer.close();
                    //model.removeRow(selectedRow);
                    //javax.swing.JOptionPane.showMessageDialog(this, "Task deleted successfuly");
                    
                    javax.swing.JOptionPane pane = new javax.swing.JOptionPane("Task deleted successfuly!",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE,
                    javax.swing.JOptionPane.DEFAULT_OPTION,
                    null, new Object[]{}, null);
                    
                    javax.swing.JDialog dialog = pane.createDialog(this, "Delete Task");
                    
                    javax.swing.Timer timer = new javax.swing.Timer(1000, tEvt -> dialog.dispose());
                    timer.setRepeats(false);
                    timer.start();
                    
                    dialog.setVisible(true);
                } catch (Exception e) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Error on deleting task.");
                }
            } else {
                return;
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Please select task to delete.");
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnMarkAsDoneActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMarkAsDoneActionPerformed
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) taskDisplay.getModel();
        int selectedRow = taskDisplay.getSelectedRow();
        
        if (selectedRow != -1) {
            String currentStatus = model.getValueAt(selectedRow, 3).toString();
            if (currentStatus.equals("Done")) {
                javax.swing.JOptionPane.showMessageDialog(this, "This task is already done");
            } else {
                int choice = javax.swing.JOptionPane.showConfirmDialog(this, "Confrim done",
                    "Confirm done", javax.swing.JOptionPane.YES_NO_OPTION);
                if (choice == javax.swing.JOptionPane.YES_OPTION) {
                    try {
                        model.setValueAt("Done", selectedRow, 3);
                        BufferedWriter writer = new BufferedWriter(new FileWriter("Task.txt", false));
                        for (int i = 0; i < model.getRowCount(); i++) {
                            String subject = model.getValueAt(i, 0).toString();
                            String task = model.getValueAt(i, 1).toString();
                            String date = model.getValueAt(i, 2).toString();
                            String status = model.getValueAt(i, 3).toString();
                        
                            writer.write(subject + "," + task + "," + date + "," + status);
                            writer.newLine();
                        }
                        writer.close();
                        
                        javax.swing.JOptionPane pane = new javax.swing.JOptionPane("Task marked as Done!",
                        javax.swing.JOptionPane.INFORMATION_MESSAGE,
                        javax.swing.JOptionPane.DEFAULT_OPTION,
                        null, new Object[]{}, null);
                        
                        javax.swing.JDialog dialog = pane.createDialog(this, "Marking task");
                        
                        javax.swing.Timer timer = new javax.swing.Timer(1000, tEvt -> dialog.dispose());
                        timer.setRepeats(false);
                        timer.start();
                    
                        dialog.setVisible(true);
                    } catch (Exception e) {
                        javax.swing.JOptionPane.showMessageDialog(this, "Error on marking task done");
                    }
                } else {
                    return;
                }
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Please select a task first.");
        }
    }//GEN-LAST:event_btnMarkAsDoneActionPerformed

