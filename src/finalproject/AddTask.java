    private void txtSaveTaskActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtSaveTaskActionPerformed
        String subject = txtSubject.getText().trim();
        String task = txtTask.getText().trim();
        String dueDate = txtDueDate.getText().trim();
        String status = "Pending...";
        
        if (subject.isEmpty() || task.isEmpty() || dueDate.contains("_")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please don't leave a black.");
        } else {
            try {
                BufferedWriter writer = new BufferedWriter(new FileWriter("Task.txt", true));
                writer.write(subject + "," + task + "," + dueDate + "," + status);
                writer.newLine();
                writer.close();
            } catch (Exception e) {
                javax.swing.JOptionPane.showMessageDialog(this, "Error!");
                return;
            }
            if (dashboard != null) {
                javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel)dashboard.taskDisplay.getModel();
                model.addRow(new Object[]{subject, task, dueDate, status});
            }
            //javax.swing.JOptionPane.showMessageDialog(this, "Added sucessfully!");
            //this.dispose();
            
            javax.swing.JOptionPane pane = new javax.swing.JOptionPane("Task added successfully",
            javax.swing.JOptionPane.INFORMATION_MESSAGE,
            javax.swing.JOptionPane.DEFAULT_OPTION, null, new Object[]{}, null);
            
            javax.swing.JDialog dialog = pane.createDialog(this, "Success");
            
            javax.swing.Timer timer = new javax.swing.Timer(1000, tEvt -> dialog.dispose());
            timer.setRepeats(false);
            timer.start();
            
            dialog.setVisible(true);
            this.dispose();
        }
    }//GEN-LAST:event_txtSaveTaskActionPerformed

